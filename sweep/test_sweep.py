def test_build_config_temperature():
    out = build_config(BASE, [("config.temperature", [0.25, 0.5, 0.75, 1.0])], [], "GSM8k")
    assert out["description"] == "GSM8k - sweep temperature [0.25, 0.5, 0.75, 1.0] (qwen3-vl:4b)"
    assert [p["config"]["temperature"] for p in out["providers"]] == [0.25, 0.5, 0.75, 1.0]
    assert [p["label"] for p in out["providers"]] == [
        "temperature=0.25",
        "temperature=0.5",
        "temperature=0.75",
        "temperature=1.0",
    ]
    # Everything else is copied unchanged, in order.
    assert list(out) == ["description", "prompts", "providers", "tests", "defaultTest"]
    for key in ("prompts", "tests", "defaultTest"):
        assert out[key] == BASE[key]
    # Other provider settings come from the first provider.
    assert all(p["config"]["seed"] == 512 and p["config"]["think"] is False for p in out["providers"])


