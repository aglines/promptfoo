import pytest

import copy

import yaml

from sweep import SCHEMA_LINE, build_config, main, model_name, parse_value, set_path


@pytest.mark.parametrize(
    "raw, expected",
    [
        ("0.5", 0.5),
        ("1", 1),
        ("1.0", 1.0),
        ("true", True),
        ("false", False),
        ("low", "low"),
        ("qwen3-vl:4b", "qwen3-vl:4b"),
        ("", ""),
    ],
)
def test_parse_value(raw, expected):
    got = parse_value(raw)
    assert got == expected
    assert type(got) is type(expected)


def test_set_path_existing_key():
    p = {"id": "x", "config": {"temperature": 0.25, "seed": 512}}
    set_path(p, "config.temperature", 0.5)
    assert p == {"id": "x", "config": {"temperature": 0.5, "seed": 512}}


def test_set_path_creates_missing_keys():
    p = {"id": "x"}
    set_path(p, "config.options.top_p", 0.9)
    assert p == {"id": "x", "config": {"options": {"top_p": 0.9}}}


def test_set_path_top_level():
    p = {"id": "x"}
    set_path(p, "id", "y")
    assert p == {"id": "y"}


def test_set_path_through_scalar_errors():
    with pytest.raises(ValueError):
        set_path({"config": 3}, "config.temperature", 0.5)


def test_set_path_empty_segment_errors():
    with pytest.raises(ValueError):
        set_path({}, "config..temperature", 0.5)


BASE = {
    "description": "GSM8k - sweep temperature",
    "prompts": ["Answer with only the number: {{question}}"],
    "providers": [
        {"id": "ollama:chat:qwen3-vl:4b", "config": {"seed": 512, "temperature": 0.25, "think": False}},
        {"id": "ollama:chat:qwen3-vl:4b", "config": {"seed": 512, "temperature": 0.5, "think": False}},
    ],
    "tests": "file://load_gsm8k.py:create_tests",
    "defaultTest": {"assert": [{"type": "python", "value": "file://numeric_match.py"}]},
}


@pytest.mark.parametrize(
    "provider_id, expected",
    [
        ("ollama:chat:qwen3-vl:4b", "qwen3-vl:4b"),
        ("ollama:qwen3:4b", "qwen3:4b"),
        ("openai:chat:gpt-4o", "gpt-4o"),
        ("openai:gpt-4o", "gpt-4o"),
        ("echo", "echo"),
    ],
)
def test_model_name(provider_id, expected):
    assert model_name(provider_id) == expected


def test_build_config_temperature():
    out = build_config(BASE, "config.temperature", [0.25, 0.5, 0.75, 1.0], "GSM8k")
    assert out["description"] == "GSM8k - sweep temperature [0.25, 0.5, 0.75, 1.0] (qwen3-vl:4b)"
    assert [p["config"]["temperature"] for p in out["providers"]] == [0.25, 0.5, 0.75, 1.0]
    assert [p["label"] for p in out["providers"]] == [
        "temperature=0.25",
        "temperature=0.5",
        "temperature=0.75",
        "temperature=1.0",
    ]
    # Everything else is copied unchanged, in order.
    assert list(out) == ["description", "prompts", "providers", "tests", "defaultTest"]
    for key in ("prompts", "tests", "defaultTest"):
        assert out[key] == BASE[key]
    # Other provider settings come from the first provider.
    assert all(p["config"]["seed"] == 512 and p["config"]["think"] is False for p in out["providers"])


def test_build_config_does_not_mutate_base():
    before = copy.deepcopy(BASE)
    build_config(BASE, "config.top_p", [0.9], "X")
    assert BASE == before


def test_build_config_bool_values_and_new_key():
    out = build_config(BASE, "config.think", [True, False], "GSM8k")
    assert [p["config"]["think"] for p in out["providers"]] == [True, False]
    assert [p["label"] for p in out["providers"]] == ["think=true", "think=false"]
    assert out["description"] == "GSM8k - sweep think [true, false] (qwen3-vl:4b)"


def test_build_config_string_provider():
    base = {"providers": ["ollama:chat:qwen3-vl:4b"]}
    out = build_config(base, "config.temperature", [0.1], "")
    assert out["providers"] == [{"id": "ollama:chat:qwen3-vl:4b", "config": {"temperature": 0.1}, "label": "temperature=0.1"}]
    assert out["description"] == "sweep temperature [0.1] (qwen3-vl:4b)"


def test_build_config_no_providers_errors():
    with pytest.raises(ValueError):
        build_config({"prompts": ["x"]}, "config.temperature", [0.1], "X")


def test_main_writes_default_config_next_to_base(tmp_path, capsys):
    base_file = tmp_path / "base.yaml"
    base_file.write_text(yaml.safe_dump(BASE, sort_keys=False))
    main([str(base_file), "--path", "config.seed", "--values", "1", "2", "3"])
    out_file = tmp_path / "promptfooconfig.yaml"
    text = out_file.read_text()
    assert text.startswith(SCHEMA_LINE + "\n# Generated by: python sweep/sweep.py ")
    cfg = yaml.safe_load(text)
    assert cfg["description"] == "GSM8k - sweep seed [1, 2, 3] (qwen3-vl:4b)"
    assert [p["config"]["seed"] for p in cfg["providers"]] == [1, 2, 3]
    assert "using the first" in capsys.readouterr().err


def test_main_name_override_and_output(tmp_path):
    base_file = tmp_path / "base.yaml"
    base_file.write_text(yaml.safe_dump({"providers": [{"id": "openai:gpt-4o"}]}))
    out_file = tmp_path / "custom.yaml"
    main([str(base_file), "--path", "config.max_tokens", "--values", "64", "-o", str(out_file), "--name", "Demo"])
    cfg = yaml.safe_load(out_file.read_text())
    assert cfg["description"] == "Demo - sweep max_tokens [64] (gpt-4o)"


def test_main_overwrites_previously_generated_output(tmp_path):
    base_file = tmp_path / "base.yaml"
    base_file.write_text(yaml.safe_dump(BASE, sort_keys=False))
    main([str(base_file), "--path", "config.seed", "--values", "1"])
    main([str(base_file), "--path", "config.seed", "--values", "2"])
    cfg = yaml.safe_load((tmp_path / "promptfooconfig.yaml").read_text())
    assert [p["config"]["seed"] for p in cfg["providers"]] == [2]


def test_main_refuses_to_overwrite_hand_written_config(tmp_path):
    base_file = tmp_path / "base.yaml"
    base_file.write_text(yaml.safe_dump(BASE, sort_keys=False))
    hand_written = tmp_path / "promptfooconfig.yaml"
    hand_written.write_text("description: mine\n")
    with pytest.raises(SystemExit):
        main([str(base_file), "--path", "config.seed", "--values", "1"])
    assert hand_written.read_text() == "description: mine\n"
    main([str(base_file), "--path", "config.seed", "--values", "1", "--force"])
    assert yaml.safe_load(hand_written.read_text())["providers"][0]["config"]["seed"] == 1


def test_main_refuses_to_overwrite_base(tmp_path):
    base_file = tmp_path / "promptfooconfig.yaml"
    base_file.write_text(yaml.safe_dump(BASE, sort_keys=False))
    with pytest.raises(SystemExit):
        main([str(base_file), "--path", "config.seed", "--values", "1", "--force"])
    assert yaml.safe_load(base_file.read_text()) == BASE


def test_build_config_sweep_provider_id():
    out = build_config(BASE, "id", ["ollama:chat:qwen3-vl:4b", "ollama:chat:qwen3.5:4b"], "GSM8k")
    assert [p["id"] for p in out["providers"]] == ["ollama:chat:qwen3-vl:4b", "ollama:chat:qwen3.5:4b"]
    assert [p["label"] for p in out["providers"]] == ["id=qwen3-vl:4b", "id=qwen3.5:4b"]
    assert out["description"] == "GSM8k - sweep id [qwen3-vl:4b, qwen3.5:4b]"
    # Config from the template is kept for every provider.
    assert all(p["config"]["temperature"] == 0.25 for p in out["providers"])
