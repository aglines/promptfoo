"""Generate a promptfoo config that sweeps provider settings over every combination of values.

Usage (from the repo root):
    uv run --project sweep python sweep/sweep.py gsm8k-eval/base.yaml \
        --sweep id=ollama:chat:qwen3-vl:4b,ollama:chat:qwen3.5:4b \
        --sweep config.think=false,true \
        --set config.num_predict=4096

`--path P --values V1 V2` is shorthand for one `--sweep P=V1,V2`.

By default the result is written to <base dir>/promptfooconfig.yaml, the file promptfoo
runs when no -c is given. The base config is the template and is never overwritten.
"""

import argparse
import copy
import itertools
import json
import os
import shlex
import sys
import urllib.error
import urllib.request
from pathlib import Path

import yaml

SCHEMA_LINE = "# yaml-language-server: $schema=https://promptfoo.dev/config-schema.json"
GENERATED_MARKER = "# Generated by: "
DEFAULT_OUTPUT_NAME = "promptfooconfig.yaml"
DEFAULT_MODELS_FILE = Path(__file__).resolve().parent / "models.yaml"
# Values Ollama accepts for `think` (src/providers/ollama.ts). Levels are model-specific.
THINK_LEVELS = ("low", "medium", "high", "max")
# Same env var and default the promptfoo Ollama provider uses.
OLLAMA_URL = os.environ.get("OLLAMA_BASE_URL") or "http://localhost:11434"
# Second id segment that names an API type rather than part of the model name,
# e.g. ollama:chat:qwen3-vl:4b or openai:chat:gpt-4o.
API_TYPES = {"chat", "completion", "completions", "embedding", "embeddings", "responses"}


def parse_value(s):
    """Parse a CLI string as a YAML scalar: '0.5' -> 0.5, 'true' -> True, 'low' -> 'low'."""
    return yaml.safe_load(s) if s.strip() else s


def set_path(obj, dotted, value):
    """Set obj[a][b][c] = value for dotted 'a.b.c', creating missing dicts."""
    keys = dotted.split(".")
    if not all(keys):
        raise ValueError(f"Invalid path: {dotted!r}")
    for key in keys[:-1]:
        child = obj.get(key)
        if child is None:
            child = obj[key] = {}
        elif not isinstance(child, dict):
            raise ValueError(f"Cannot set {dotted!r}: {key!r} is not a mapping")
        obj = child
    obj[keys[-1]] = value


def fmt(value):
    """Format a value for labels and descriptions: True -> 'true', 0.25 -> '0.25'."""
    if isinstance(value, bool):
        return str(value).lower()
    return str(value)


def model_name(provider_id):
    """'ollama:chat:qwen3-vl:4b' -> 'qwen3-vl:4b'; 'openai:gpt-4o' -> 'gpt-4o'."""
    parts = provider_id.split(":")
    if len(parts) >= 3 and parts[1] in API_TYPES:
        return ":".join(parts[2:])
    if len(parts) >= 2:
        return ":".join(parts[1:])
    return provider_id


def description_prefix(base, base_dir):
    desc = base.get("description")
    if isinstance(desc, str) and desc.strip():
        return desc.split(" - ", 1)[0].strip()
    return base_dir.name


def parse_assignment(arg):
    """'config.think=false,true' -> ('config.think', 'false,true')."""
    path, sep, rhs = arg.partition("=")
    if not sep or not path:
        raise ValueError(f"Expected PATH=VALUE, got {arg!r}")
    return path, rhs


def parse_sweep(arg):
    """'config.think=false,true' -> ('config.think', [False, True])."""
    path, rhs = parse_assignment(arg)
    items = rhs.split(",")
    if not all(item.strip() for item in items):
        raise ValueError(f"Empty value in --sweep {arg!r}")
    return path, [parse_value(item) for item in items]


def parse_set(arg):
    """'config.num_predict=4096' -> ('config.num_predict', 4096)."""
    path, rhs = parse_assignment(arg)
    return path, parse_value(rhs)


def check_axes(axes, sets):
    if not axes:
        raise ValueError("Nothing to sweep: pass --sweep PATH=V1,V2,... (or --path/--values)")
    swept = [path for path, _ in axes]
    for path in swept:
        if swept.count(path) > 1:
            raise ValueError(f"{path!r} is swept more than once")
    for path, values in axes:
        if not values:
            raise ValueError(f"No values to sweep for {path!r}")
    for path, _ in sets:
        if path in swept:
            raise ValueError(f"{path!r} is both swept and --set")


def shown(path, value):
    """How a value appears in labels and descriptions; provider ids are shortened to the model."""
    return model_name(str(value)) if path == "id" else fmt(value)


def leaf(path):
    return path.split(".")[-1]


def build_config(base, axes, sets, name):
    """Return a new config dict: `base` with providers replaced by one per combination.

    `axes` is a list of (path, values) to sweep; `sets` is a list of (path, value)
    applied to every provider.
    """
    check_axes(axes, sets)
    providers = base.get("providers")
    if not providers:
        raise ValueError("Base config has no providers")
    template = copy.deepcopy(providers[0])
    if isinstance(template, str):
        template = {"id": template}
    for path, value in sets:
        set_path(template, path, value)

    swept = []
    for combo in itertools.product(*(values for _, values in axes)):
        provider = copy.deepcopy(template)
        parts = []
        for (path, _), value in zip(axes, combo):
            set_path(provider, path, value)
            parts.append(f"{leaf(path)}={shown(path, value)}")
        provider["label"] = " ".join(parts)
        swept.append(provider)

    summary = "sweep " + " x ".join(
        f"{leaf(path)} [{', '.join(shown(path, v) for v in values)}]" for path, values in axes
    )
    description = f"{name} - {summary}" if name else summary
    if all(path != "id" for path, _ in axes):
        model = model_name(str(template.get("id", "")))
        if model:
            description += f" ({model})"

    out = {"description": description}
    for key, val in base.items():
        if key == "description":
            continue
        out[key] = swept if key == "providers" else val
    return out


def is_think_value(value):
    return isinstance(value, bool) or value in THINK_LEVELS


def load_model_rules(path):
    """Load models.yaml: {model_name: {think: [allowed values]}}. A missing file means no rules."""
    if not path.exists():
        return {}
    rules = yaml.safe_load(path.read_text()) or {}
    if not isinstance(rules, dict):
        raise ValueError(f"{path}: expected a mapping of model name -> rules")
    for model, rule in rules.items():
        if not isinstance(rule, dict):
            raise ValueError(f"{path}: rules for {model!r} must be a mapping")
        think = rule.get("think")
        if think is None:
            continue
        if not isinstance(think, list) or not all(is_think_value(v) for v in think):
            raise ValueError(
                f"{path}: think for {model!r} must be a list of true, false, {', '.join(THINK_LEVELS)}"
            )
    return rules


def same_value(a, b):
    """Equality that keeps True distinct from 1."""
    return type(a) is type(b) and a == b


class OllamaError(Exception):
    """Ollama could not be reached."""


def ollama_show(model):
    """Return Ollama's /api/show info for `model`, or None if it is not pulled."""
    request = urllib.request.Request(
        f"{OLLAMA_URL}/api/show",
        data=json.dumps({"model": model}).encode(),
        headers={"Content-Type": "application/json"},
    )
    try:
        with urllib.request.urlopen(request, timeout=10) as response:
            return json.load(response)
    except urllib.error.HTTPError as e:
        if e.code == 404:
            return None
        raise OllamaError(f"HTTP {e.code}") from e
    except (urllib.error.URLError, OSError) as e:
        raise OllamaError(str(getattr(e, "reason", e))) from e


def get_think(provider):
    config = provider.get("config")
    return config.get("think") if isinstance(config, dict) else None


def check_provider(provider, rules):
    """Return a list of problems with one generated provider (empty if it is allowed).

    Checks only the local rules; the Ollama lookup happens in `validate`.
    """
    provider_id = str(provider.get("id", ""))
    model = model_name(provider_id)
    label = provider.get("label", model)
    if not provider_id.startswith("ollama:"):
        return [f"{label}: {provider_id!r} is not an Ollama provider; only ollama: providers are supported"]
    think = get_think(provider)
    if think is None:
        return []
    if not is_think_value(think):
        return [f"{label}: think={fmt(think)} is not a valid value (true, false, {', '.join(THINK_LEVELS)})"]
    allowed = (rules.get(model) or {}).get("think")
    if allowed is None:
        if isinstance(think, bool):
            return []
        return [f"{label}: think={think} is not allowed for {model}; it is not in models.yaml, so only true/false are allowed"]
    if not any(same_value(think, a) for a in allowed):
        shown_allowed = ", ".join(fmt(a) for a in allowed)
        return [f"{label}: think={fmt(think)} is not allowed for {model}; models.yaml allows [{shown_allowed}]"]
    return []


def validate(providers, rules, show_model=None):
    """Return every problem across the generated providers.

    `show_model(model)` returns Ollama's /api/show info, or None if the model is not
    pulled, and raises OllamaError if Ollama is unreachable. If it is None, only the
    local rules are checked.
    """
    problems = [problem for p in providers for problem in check_provider(p, rules)]
    if show_model is None:
        return problems

    info = {}
    for provider in providers:
        provider_id = str(provider.get("id", ""))
        if not provider_id.startswith("ollama:"):
            continue
        model = model_name(provider_id)
        label = provider.get("label", model)
        if model not in info:
            try:
                info[model] = show_model(model)
            except OllamaError as e:
                problems.append(f"Ollama not reachable at {OLLAMA_URL}: {e}")
                return problems
        if info[model] is None:
            problems.append(f"{label}: {model} is not pulled in Ollama")
            continue
        think = get_think(provider)
        if think not in (None, False) and "thinking" not in (info[model].get("capabilities") or []):
            problems.append(f"{label}: think={fmt(think)} but {model} has no 'thinking' capability in Ollama")
    return problems


def render(config, command):
    body = yaml.safe_dump(config, sort_keys=False, allow_unicode=True, width=100)
    return f"{SCHEMA_LINE}\n{GENERATED_MARKER}{command}\n{body}"


def is_generated(path):
    """True if `path` was written by this script (its header has the marker)."""
    with open(path) as f:
        return any(line.startswith(GENERATED_MARKER) for line, _ in zip(f, range(5)))


def main(argv=None, show_model=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("base", type=Path, help="Base promptfoo config (its first provider is the template)")
    parser.add_argument(
        "--sweep",
        action="append",
        default=[],
        metavar="PATH=V1,V2,...",
        help="Provider path and values to sweep (repeatable; every combination is generated)",
    )
    parser.add_argument(
        "--set",
        action="append",
        default=[],
        metavar="PATH=VALUE",
        help="Fixed provider value applied to every generated provider (repeatable)",
    )
    parser.add_argument("--path", help="Shorthand for one sweep: dotted path inside the provider")
    parser.add_argument("--values", nargs="+", help="Values for --path, parsed as YAML scalars")
    parser.add_argument("-o", "--output", type=Path, help=f"Output file (default: <base dir>/{DEFAULT_OUTPUT_NAME})")
    parser.add_argument("--force", action="store_true", help="Overwrite an output file this script did not generate")
    parser.add_argument("--name", help="Description prefix (default: base description before ' - ')")
    parser.add_argument(
        "--models",
        type=Path,
        help=f"Per-model rules for allowed values (default: {DEFAULT_MODELS_FILE.name} next to sweep.py)",
    )
    args = parser.parse_args(argv)

    base = yaml.safe_load(args.base.read_text())
    if not isinstance(base, dict):
        parser.error(f"{args.base} is not a YAML mapping")
    providers = base.get("providers") or []
    if len(providers) > 1:
        print(f"warning: base has {len(providers)} providers; using the first as the template", file=sys.stderr)

    base_dir = args.base.resolve().parent
    name = args.name if args.name is not None else description_prefix(base, base_dir)
    if (args.path is None) != (args.values is None):
        parser.error("--path and --values must be used together")
    try:
        axes = [parse_sweep(arg) for arg in args.sweep]
        if args.path is not None:
            axes.append((args.path, [parse_value(v) for v in args.values]))
        sets = [parse_set(arg) for arg in args.set]
        config = build_config(base, axes, sets, name)
        if args.models is not None and not args.models.exists():
            raise ValueError(f"--models file not found: {args.models}")
        rules = load_model_rules(args.models or DEFAULT_MODELS_FILE)
    except ValueError as e:
        parser.error(str(e))

    output = args.output or base_dir / DEFAULT_OUTPUT_NAME
    if output.resolve() == args.base.resolve():
        parser.error(f"output {output} is the base config; the template must not be overwritten")

    problems = validate(config["providers"], rules, show_model or ollama_show)
    if problems:
        print("refused: these combinations are not supported, nothing was written:", file=sys.stderr)
        for problem in problems:
            print(f"  - {problem}", file=sys.stderr)
        if output.exists() and is_generated(output):
            # A stale sweep would otherwise run on the next plain `promptfoo eval`.
            output.unlink()
            print(f"removed stale {output}; a plain eval will now find no config", file=sys.stderr)
        sys.exit(2)
    if output.exists() and not args.force and not is_generated(output):
        parser.error(f"{output} exists and was not generated by this script; move it or pass --force")
    if output.resolve().parent != base_dir:
        print(
            f"warning: {output} is not in {base_dir}; relative file:// paths in the config may not resolve",
            file=sys.stderr,
        )

    command = shlex.join(["python", *sys.argv] if argv is None else ["python", "sweep/sweep.py", *argv])
    output.write_text(render(config, command))
    print(f"wrote {output} ({len(config['providers'])} providers)")


if __name__ == "__main__":
    main()
