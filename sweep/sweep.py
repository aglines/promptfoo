"""Generate a promptfoo config that sweeps one provider config key over several values.

Usage (from the repo root):
    uv run --project sweep python sweep/sweep.py gsm8k-eval/base.yaml \
        --path config.temperature --values 0.25 0.5 0.75 1.0

By default the result is written to <base dir>/promptfooconfig.yaml, the file promptfoo
runs when no -c is given. The base config is the template and is never overwritten.
"""

import argparse
import copy
import shlex
import sys
from pathlib import Path

import yaml

SCHEMA_LINE = "# yaml-language-server: $schema=https://promptfoo.dev/config-schema.json"
GENERATED_MARKER = "# Generated by: "
DEFAULT_OUTPUT_NAME = "promptfooconfig.yaml"
# Second id segment that names an API type rather than part of the model name,
# e.g. ollama:chat:qwen3-vl:4b or openai:chat:gpt-4o.
API_TYPES = {"chat", "completion", "completions", "embedding", "embeddings", "responses"}


def parse_value(s):
    """Parse a CLI string as a YAML scalar: '0.5' -> 0.5, 'true' -> True, 'low' -> 'low'."""
    return yaml.safe_load(s) if s.strip() else s


def set_path(obj, dotted, value):
    """Set obj[a][b][c] = value for dotted 'a.b.c', creating missing dicts."""
    keys = dotted.split(".")
    if not all(keys):
        raise ValueError(f"Invalid path: {dotted!r}")
    for key in keys[:-1]:
        child = obj.get(key)
        if child is None:
            child = obj[key] = {}
        elif not isinstance(child, dict):
            raise ValueError(f"Cannot set {dotted!r}: {key!r} is not a mapping")
        obj = child
    obj[keys[-1]] = value


def fmt(value):
    """Format a value for labels and descriptions: True -> 'true', 0.25 -> '0.25'."""
    if isinstance(value, bool):
        return str(value).lower()
    return str(value)


def model_name(provider_id):
    """'ollama:chat:qwen3-vl:4b' -> 'qwen3-vl:4b'; 'openai:gpt-4o' -> 'gpt-4o'."""
    parts = provider_id.split(":")
    if len(parts) >= 3 and parts[1] in API_TYPES:
        return ":".join(parts[2:])
    if len(parts) >= 2:
        return ":".join(parts[1:])
    return provider_id


def description_prefix(base, base_dir):
    desc = base.get("description")
    if isinstance(desc, str) and desc.strip():
        return desc.split(" - ", 1)[0].strip()
    return base_dir.name


def build_config(base, path, values, name):
    """Return a new config dict: `base` with providers replaced by one per value."""
    providers = base.get("providers")
    if not providers:
        raise ValueError("Base config has no providers")
    template = providers[0]
    if isinstance(template, str):
        template = {"id": template}
    leaf = path.split(".")[-1]

    swept = []
    for value in values:
        provider = copy.deepcopy(template)
        set_path(provider, path, value)
        shown = model_name(str(value)) if path == "id" else fmt(value)
        provider["label"] = f"{leaf}={shown}"
        swept.append(provider)

    if path == "id":
        # Sweeping the provider itself: list model names, no fixed-model suffix.
        summary = f"sweep id [{', '.join(model_name(str(v)) for v in values)}]"
        model = ""
    else:
        summary = f"sweep {leaf} [{', '.join(fmt(v) for v in values)}]"
        model = model_name(str(template.get("id", "")))
    description = f"{name} - {summary}" if name else summary
    if model:
        description += f" ({model})"

    out = {"description": description}
    for key, val in base.items():
        if key == "description":
            continue
        out[key] = swept if key == "providers" else val
    return out


def render(config, command):
    body = yaml.safe_dump(config, sort_keys=False, allow_unicode=True, width=100)
    return f"{SCHEMA_LINE}\n{GENERATED_MARKER}{command}\n{body}"


def is_generated(path):
    """True if `path` was written by this script (its header has the marker)."""
    with open(path) as f:
        return any(line.startswith(GENERATED_MARKER) for line, _ in zip(f, range(5)))


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("base", type=Path, help="Base promptfoo config (its first provider is the template)")
    parser.add_argument("--path", required=True, help="Dotted path inside the provider, e.g. config.temperature")
    parser.add_argument("--values", required=True, nargs="+", help="Values to sweep, parsed as YAML scalars")
    parser.add_argument("-o", "--output", type=Path, help=f"Output file (default: <base dir>/{DEFAULT_OUTPUT_NAME})")
    parser.add_argument("--force", action="store_true", help="Overwrite an output file this script did not generate")
    parser.add_argument("--name", help="Description prefix (default: base description before ' - ')")
    args = parser.parse_args(argv)

    base = yaml.safe_load(args.base.read_text())
    if not isinstance(base, dict):
        parser.error(f"{args.base} is not a YAML mapping")
    providers = base.get("providers") or []
    if len(providers) > 1:
        print(f"warning: base has {len(providers)} providers; using the first as the template", file=sys.stderr)

    base_dir = args.base.resolve().parent
    name = args.name if args.name is not None else description_prefix(base, base_dir)
    values = [parse_value(v) for v in args.values]
    try:
        config = build_config(base, args.path, values, name)
    except ValueError as e:
        parser.error(str(e))

    output = args.output or base_dir / DEFAULT_OUTPUT_NAME
    if output.resolve() == args.base.resolve():
        parser.error(f"output {output} is the base config; the template must not be overwritten")
    if output.exists() and not args.force and not is_generated(output):
        parser.error(f"{output} exists and was not generated by this script; move it or pass --force")
    if output.resolve().parent != base_dir:
        print(
            f"warning: {output} is not in {base_dir}; relative file:// paths in the config may not resolve",
            file=sys.stderr,
        )

    command = shlex.join(["python", *sys.argv] if argv is None else ["python", "sweep/sweep.py", *argv])
    output.write_text(render(config, command))
    print(f"wrote {output} ({len(values)} providers)")


if __name__ == "__main__":
    main()
